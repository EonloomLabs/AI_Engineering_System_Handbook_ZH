"""Bundle i18n/locales/*.json into assets/i18n-data.js.

A JS bundle rather than fetched JSON so the book keeps working from file://.
Run: python3 i18n/build.py
"""
import json, sys
from pathlib import Path

# `--check` rebuilds in memory and compares, without writing. It catches the
# case that bit us once: a locale file edited after the last build, so the
# source is correct but the bundle the page actually loads is stale.
CHECK = '--check' in sys.argv

ROOT = Path(__file__).resolve().parent.parent
SRC = json.loads((ROOT / 'i18n/source.json').read_text(encoding='utf-8'))
KEYS = list(SRC['keys'])
META = SRC['_meta']


def editions():
    """Languages the whole book exists in, so the switcher can navigate to them.

    A partial edition must not be listed: the switcher would send a reader to a
    page that is not there. Completeness is measured against the canonical page
    list, so a language appears only once every page has a translated twin.
    """
    import json as _json
    units = ROOT / 'i18n/units'
    if not units.is_dir():
        return ['zh-CN']
    pages = [_json.loads(f.read_text(encoding='utf-8'))['page']
             for f in sorted(units.glob('*.json'))]
    out = ['zh-CN']
    for code in META['locales']:
        if code == 'zh-CN':
            continue
        d = ROOT / code
        if d.is_dir() and all((d / rel).exists() for rel in pages):
            out.append(code)
    return out
# Endonyms: each language named in itself, which is what a reader scans for.
NAMES = {
 'zh-CN': '简体中文', 'zh-TW': '繁體中文（台灣）', 'en': 'English', 'es': 'Español',
 'id': 'Bahasa Indonesia', 'ar': 'العربية', 'ru': 'Русский', 'vi': 'Tiếng Việt',
 'ta': 'தமிழ்', 'ja': '日本語', 'tr': 'Türkçe', 'ko': '한국어', 'hu': 'Magyar',
 'he': 'עברית', 'pt-BR': 'Português (Brasil)',
}

def main() -> int:
    tables, report, problems = {}, [], []
    for code in META['locales']:
        if code in ('zh-CN', 'en'):
            tables[code] = {k: SRC['keys'][k][code] for k in KEYS if code in SRC['keys'][k]}
        else:
            f = ROOT / 'i18n/locales' / (code + '.json')
            if not f.exists():
                problems.append((code, 'locale file missing'))
                continue
            try:
                tables[code] = json.loads(f.read_text(encoding='utf-8'))
            except json.JSONDecodeError as e:
                problems.append((code, 'invalid JSON: %s' % e))
                continue
        t = tables.get(code, {})
        missing = [k for k in KEYS if k not in t or not str(t.get(k, '')).strip()]
        extra = [k for k in t if k not in KEYS]
        # Japanese and Korean legitimately use Han characters, so "contains Han"
        # cannot flag an untranslated string. Compare against the source instead:
        # a value identical to the Chinese original is the real signal.
        zh = {k: SRC['keys'][k]['zh-CN'] for k in KEYS}
        han = [] if code.startswith('zh') else [
            k for k, v in t.items()
            if k in zh and str(v).strip() == zh[k].strip()
            and k not in ('search.pageHint',)          # its examples stay Chinese on purpose
        ]
        report.append((code, len(t), len(missing), len(extra), len(han)))
        if missing: problems.append((code, 'missing %d keys: %s' % (len(missing), missing[:5])))
        if extra:   problems.append((code, 'unknown keys: %s' % extra[:5]))
        if han:     problems.append((code, 'identical to the Chinese source: %s' % han[:5]))

    out = ('/* Generated by i18n/build.py — do not edit by hand. */\n'
           'window.I18N_META=%s;\n'
           'window.I18N_STRINGS=%s;\n' % (
            json.dumps({'locales': META['locales'], 'rtl': META['rtl'],
                        'editions': editions(),
                        'names': {c: NAMES[c] for c in META['locales'] if c in NAMES}},
                       ensure_ascii=False, separators=(',', ':')),
            json.dumps(tables, ensure_ascii=False, separators=(',', ':'))))
    target = ROOT / 'assets/i18n-data.js'
    if CHECK:
        current = target.read_text(encoding='utf-8') if target.exists() else ''
        if current != out:
            problems.append(('bundle', 'assets/i18n-data.js is stale — run python3 i18n/build.py'))
    else:
        target.write_text(out, encoding='utf-8')

    print('%-8s %6s %8s %7s %11s' % ('locale', 'keys', 'missing', 'extra', 'same-as-zh'))
    for r in report:
        print('%-8s %6d %8d %7d %11d' % r)
    print('\nbundle: %.1f KB, %d locales, %d keys' % (len(out.encode()) / 1024, len(tables), len(KEYS)))
    if problems:
        print('\nPROBLEMS:')
        for c, m in problems:
            print('  %-8s %s' % (c, m))
    return 1 if problems else 0

sys.exit(main())

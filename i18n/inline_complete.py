"""Refresh the i18n blocks inlined in complete.html.

complete.html ships with no external assets, so the catalogue, runtime and
stylesheet are embedded. Run this after i18n/build.py whenever the catalogue
changes, or the single-file edition serves an older translation than the
paged edition.

The blocks are delimited by sentinel comments, installed on first run, so
repeated runs replace rather than accumulate.

Run: python3 i18n/inline_complete.py [--check]
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECK = '--check' in sys.argv
P = ROOT / 'complete.html'

# (sentinel name, source asset, text that marks where the block starts today)
BLOCKS = [
    ('i18n-css', 'assets/i18n.css', '/* i18n: switcher and RTL */', '</style>'),
    ('i18n-data', 'assets/i18n-data.js', '/* Generated by i18n/build.py', '</script>'),
    ('i18n-rt', 'assets/i18n.js', '/* Interface localisation.', '</script>'),
]


def bounds(doc, name, legacy_start, legacy_end):
    """Span to replace. Uses sentinels once installed, else the legacy anchors."""
    b, e = '/*%s:begin*/' % name, '/*%s:end*/' % name
    i = doc.find(b)
    if i != -1:
        return i + len(b), doc.index(e, i), True
    i = doc.find(legacy_start)
    if i == -1:
        raise SystemExit('cannot locate %s in complete.html' % name)
    return i, doc.index(legacy_end, i), False


def main() -> int:
    doc = P.read_text(encoding='utf-8')
    stale = []
    for name, asset, ls, le in BLOCKS:
        payload = (ROOT / asset).read_text(encoding='utf-8')
        start, end, wrapped = bounds(doc, name, ls, le)
        if doc[start:end] != payload:
            stale.append(name)
        if not CHECK:
            block = payload if wrapped else '/*%s:begin*/%s/*%s:end*/' % (name, payload, name)
            doc = doc[:start] + block + doc[end:]

    if CHECK:
        if stale:
            print('complete.html is stale for: %s — run python3 i18n/inline_complete.py'
                  % ', '.join(stale))
            return 1
        print('complete.html i18n blocks are in sync')
        return 0

    P.write_text(doc, encoding='utf-8')
    print('refreshed: %s' % (', '.join(stale) if stale else 'already in sync'))
    print('complete.html %.1f MB' % (len(doc.encode()) / 1048576))
    return 0


sys.exit(main())
